export const FOOTER_DISCLAIMER = FOOTER_DISCLAIMER_VARIANTS[0];

function hashSeed(input: string) {
  let hash = 2166136261;
  for (let i = 0; i < input.length; i += 1) {
    hash ^= input.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

export function pickFooterDisclaimer(seed: string, offset = 0) {
  const list = FOOTER_DISCLAIMER_VARIANTS;
  if (!list.length) return FOOTER_DISCLAIMER;
  const index = (hashSeed(seed || "site") + Math.max(0, offset)) % list.length;
  return list[index];
}

export function randomFooterDisclaimer(exclude?: string) {
  const list = FOOTER_DISCLAIMER_VARIANTS.filter((row) => row !== exclude);
  const pool = list.length ? list : FOOTER_DISCLAIMER_VARIANTS;
  return pool[Math.floor(Math.random() * pool.length)];
}

export function resolveFooterDisclaimer(settings?: {
  footerDisclaimer?: string;
  siteName?: string;
  siteTagline?: string;
  domain?: string;
}) {
  const custom = String(settings?.footerDisclaimer || "").trim();
  if (custom) return custom;
  const seed = [settings?.siteName, settings?.siteTagline, settings?.domain].filter(Boolean).join("|") || "magazine";
  return pickFooterDisclaimer(seed);
}
