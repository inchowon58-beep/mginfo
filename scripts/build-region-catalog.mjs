function uniq(items) {
  return [...new Set((items || []).filter(Boolean))];
}

function rowFrom(keys, official, lat, lng, landmarks, nearby, stations) {
  const keyList = uniq(keys).filter((k) => k.length >= 2 && !BLOCK.has(k));
  if (!keyList.length) return null;
  const short = keyList[0];
  return {
    keys: keyList,
    official,
    landmarks: uniq(landmarks).slice(0, 6),
    nearby: uniq(nearby).slice(0, 5),
    stations: uniq(stations).slice(0, 5),
    lat,
    lng,
    hook: `${official} 생활권에서 방문 동선을 나눠 보기 좋은`,
  };
}

